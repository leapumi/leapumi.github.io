// Run with Node.js after installing occt-import-js@0.0.23.
// An optional first argument specifies the importer module's path.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const zlib = require('node:zlib');
const initOcct = require(process.argv[2] || 'occt-import-js');

async function main() {
  const root = path.resolve(__dirname, '..');
  const source = fs.readFileSync(path.join(root, 'assets/fiexed_full_assembly_right.STEP'));
  const occt = await initOcct();
  const result = occt.ReadStepFile(source, {
    linearUnit: 'millimeter',
    linearDeflectionType: 'absolute_value',
    linearDeflection: 0.15,
    angularDeflection: 0.4
  });
  if (!result.success || !result.meshes?.length) {
    throw new Error('The STEP model could not be triangulated.');
  }
  const encode = (array) => Buffer.from(array.buffer, array.byteOffset, array.byteLength).toString('base64');
  let triangles = 0;
  const meshes = result.meshes.map((mesh) => {
    const positions = Float32Array.from(mesh.attributes.position.array);
    const normals = mesh.attributes.normal ? Float32Array.from(mesh.attributes.normal.array) : null;
    const indices = Uint32Array.from(mesh.index.array);
    if (!positions.length || positions.length % 3 || indices.length % 3 ||
        !positions.every(Number.isFinite) || (normals && !normals.every(Number.isFinite)) ||
        !indices.every((i) => i < positions.length / 3)) {
      throw new Error('Invalid geometry in the imported model.');
    }
    triangles += indices.length / 3;
    return {
      positions: encode(positions),
      normals: normals ? encode(normals) : null,
      indices: encode(indices),
      color: mesh.color || null,
      faces: (mesh.brep_faces || []).filter((face) => face.color)
        .map(({ first, last, color }) => ({ first, last, color }))
    };
  });
  const preview = {
    version: 1,
    source: 'fiexed_full_assembly_right.STEP',
    sourceSha256: crypto.createHash('sha256').update(source).digest('hex'),
    triangles,
    meshes
  };
  // A classic script also works on anonymous hosts with an opaque sandbox origin.
  // Using fetch() for binary/JSON assets on those hosts would require CORS headers.
  const compressed = zlib.gzipSync(JSON.stringify(preview), { level: 9 });
  const output = '// Generated by tools/build-cad-preview.cjs. Do not edit.\n' +
    'window.LEAPUMI_CAD_PREVIEW_GZIP = "' + compressed.toString('base64') + '";\n';
  const destination = path.join(root, 'assets/cad/hardware-preview.js');
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, output);
  console.log(JSON.stringify({ meshes: meshes.length, triangles, bytes: Buffer.byteLength(output), sourceSha256: preview.sourceSha256 }));
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
